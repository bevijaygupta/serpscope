def seed_scenarios(db: Session) -> int:
    existing = {s.key for s in db.query(DemoScenario).all()}
    created = 0
    for item in SCENARIOS:
        if item["key"] in existing:
            continue
        db.add(DemoScenario(**item))
        created += 1
    db.flush()
    return created
